  const [the, our] = B[b.key][LANG === "fr" ? 0 : 1];
  const name = the.replace(/^(le |la |l'|o |a )/, "");
  return { name: name[0].toUpperCase() + name.slice(1), the, our: our[0].toUpperCase() + our.slice(1), tothe: the };
