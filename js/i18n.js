export function t(s, v = {}) {
  const e = D[s];
  const out = (LANG !== "de" && e && e[LANG === "fr" ? 0 : 1]) || s;
  return out.replace(/\{(\w+)\}/g, (_, k) => (v[k] ?? `{${k}}`));
}
// Einzahl/Mehrzahl
export const tn = (n, one, many, v = {}) => t(n === 1 ? one : many, { n, ...v });

